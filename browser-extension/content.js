/* ── Intercept downloadable link clicks ─────────────────────────── */
document.addEventListener("click", (event) => {
  const link = event.target.closest?.("a[href]");
  if (!link) return;
  const href = link.href;
  if (!/^https?:\/\//i.test(href)) return;
  try {
    const pathname = new URL(href).pathname;
    if (!DOWNLOADABLE.test(pathname)) return;
  } catch { return; }

  event.preventDefault();
  event.stopPropagation();

  const filename = decodeURIComponent(href.split("/").filter(Boolean).pop()?.split("?")[0] || "");
  sendRuntimeMessage({ type: "speusis-download", url: href, filename: filename || undefined });
}, true);

/* ── Listen for MAIN-world network intercept messages ───────────── */
window.addEventListener("message", (e) => {
  if (e.source !== window || !e.data) return;

  if (e.data.__speusisYtFormats) {
    if (!isYouTubeVideoPage()) return;
    const formats = e.data.formats || [];
    const responseVideoId = String(e.data.videoId || "");
    if (responseVideoId && responseVideoId !== ytCurrentVideoId) {
      resetYouTubeCaptureState();
      ytCurrentVideoId = responseVideoId;
    }
    ytKnownFormatCount = formats.length;
    ytLockedFormatCount = formats.filter(f => f.locked).length;
    formats.forEach((f) => {
      if (!f.itag) return;
      const kind = f.hasVideo && f.hasAudio ? "combined" : f.hasVideo ? "video" : "audio";
      if (f.url) {
        if (f.hasVideo && !f.hasAudio) {
          ytPendingFormats.set(String(f.itag), {
            itag: String(f.itag),
            quality: f.quality || String(f.itag),
            type: "MP4",
            pending: true,
            kind: "video",
            timestamp: Date.now(),
          });
        } else {
          ytPendingFormats.delete(String(f.itag));
        }
      } else if (f.hasVideo) {
        ytPendingFormats.set(String(f.itag), {
          itag: String(f.itag),
          quality: f.quality || String(f.itag),
          type: "MP4",
          pending: true,
          kind,
          timestamp: Date.now(),
        });
      }
    });
    /* Plain URLs are already downloadable.  The previous code counted
     * them only for the hint and discarded them, which is why the panel
     * showed no quality ladder even when YouTube supplied usable URLs. */
    formats.filter(f => f.url && f.itag).forEach((f) => {
      recordYouTubeStream(
        f.url,
        String(f.itag),
        f.quality || String(f.itag),
        f.hasVideo && f.hasAudio ? "combined" : f.hasVideo ? "video" : "audio",
      );
    });
    updateStreamBadge();
    return;
  }
  if (e.data.__speusisYtCaptions) {
    (e.data.captions || []).forEach(recordYouTubeSubtitle);
    return;
  }
  if (e.data.__speusisYtLockedCipherData) {
    // Hand off to the service worker, which is the actual network caller
    // (see interceptor.js's v0.27 comment for why it's not called from
    // here directly). Best-effort - if this fails or the service worker
    // doesn't respond, formats simply stay locked, same as before.
    sendRuntimeMessage({
      type: "speusis-resolve-yt-cipher",
      playerUrl: e.data.playerUrl,
      formats: e.data.formats,
    }).catch(() => {});
    return;
  }
  if (e.data.__speusis) {
    if (location.hostname.includes("youtube.com") && !isYouTubeVideoPage()) {
      hideBadge();
      return;
    }
    if (e.data.isYouTube && e.data.ytItag) {
      recordYouTubeStream(e.data.url, e.data.ytItag, e.data.ytQuality || e.data.ytItag, e.data.ytKind, e.data.fileSize);
    } else {
      checkStreamUrl(e.data.url);
    }
    return;
  }
});

