function dedupeYouTubeQualityStreams(streams) {
  if (!location.hostname.includes("youtube.com")) return streams;
  const chosen = new Map();
  const result = [];
  for (const stream of streams) {
    if (stream.type !== "MP4" || !stream.quality) {
      result.push(stream);
      continue;
    }
    const match = String(stream.quality).match(/(\d{3,4}p)(?:\s+(\d+)\s*fps)?/i);
    const key = match
      ? `${match[1].toLowerCase()}-${match[2] || "default"}`
      : String(stream.quality).toLowerCase();
    const previous = chosen.get(key);
    if (!previous) {
      chosen.set(key, stream);
      result.push(stream);
      continue;
    }
    /* Prefer a direct progressive file over a mux request when both are
     * the same visible quality. Otherwise keep the first real URL. */
    if (previous.needsMux && !stream.needsMux) {
      const index = result.indexOf(previous);
      if (index >= 0) result[index] = stream;
      chosen.set(key, stream);
    }
  }
  return result;
}

