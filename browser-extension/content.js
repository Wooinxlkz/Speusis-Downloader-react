/* ── YouTube adaptive-format pools (v0.23) ──────────────────────────
 * Combined (progressive) itags still go straight into detectedStreams,
 * unchanged from before. Adaptive video-only / audio-only itags land
 * here first, keyed by itag, as they're actually requested by the real
 * player. Once at least one video itag AND one audio itag have been
 * captured, they're paired into a "needs mux" entry in detectedStreams —
 * two URLs the desktop app downloads and merges into one file. */
const ytAdaptiveVideo = new Map(); // itag -> {itag, quality, url}
const ytAdaptiveAudio = new Map(); // itag -> {itag, quality, url}
const ytPendingFormats = new Map(); // itag -> {itag, quality, kind, pending}
let ytCurrentVideoId = "";
let ytKnownFormatCount = 0;        // from the full player-response scan, for the "+N more" hint
let ytLockedFormatCount = 0;

function pickBestAudio() {
  // Prefer higher-bitrate AAC/Opus if more than one audio itag got captured.
  const RANK = { "141": 0, "251": 1, "140": 2, "250": 3, "139": 4, "249": 5 };
  let best = null;
  for (const a of ytAdaptiveAudio.values()) {
    if (!best || (RANK[a.itag] ?? 9) < (RANK[best.itag] ?? 9)) best = a;
  }
  return best;
}

function rebuildYouTubeMuxPairs() {
  const audio = pickBestAudio();
  for (const v of ytAdaptiveVideo.values()) {
    const key = `yt-mux-${v.itag}`;
    if (audio) {
      detectedStreams.set(key, {
        url: v.url,           // representative URL (used for display/ranking)
        videoUrl: v.url,
        audioUrl: audio.url,
        needsMux: true,
        type: "MP4",
        quality: `${v.quality} (muxed)`,
        // Approximate: video-only stream size dominates the final muxed
        // file, so this is close enough for display purposes even though
        // the audio track adds a bit more.
        fileSize: (v.fileSize && audio.fileSize) ? v.fileSize + audio.fileSize : (v.fileSize || null),
        timestamp: Date.now(),
      });
      ytPendingFormats.delete(String(v.itag));
    } else {
      /* Keep every discovered resolution visible while the audio request is
       * still in flight.  The old code dropped video-only formats here,
       * leaving only the one progressive stream that arrived first. */
      ytPendingFormats.set(String(v.itag), {
        itag: String(v.itag),
        quality: v.quality,
        type: "MP4",
        pending: true,
        kind: "video",
        timestamp: Date.now(),
      });
    }
  }
  if (audio || ytAdaptiveVideo.size) updateStreamBadge();
}

function recordYouTubeSubtitle(sub) {
  if (!isYouTubeVideoPage()) return;
  const key = `yt-sub-${sub.lang}`;
  if (detectedStreams.has(key)) return;
  detectedStreams.set(key, {
    url: sub.url,
    type: "Subtitle",
    quality: `${sub.label || sub.lang}${sub.autoGenerated ? " (auto)" : ""}`,
    timestamp: Date.now(),
  });
  updateStreamBadge();
}

