let _ytActiveVideoKey = "";
function handleYouTubeActiveVideo(media) {
  // v0.27 fix: attach the hover listener to ANY active-looking <video>
  // unconditionally, regardless of its src. YouTube plays virtually
  // everything - including homepage/grid hover-preview thumbnails, not
  // just the main watch-page player - through MediaSource Extensions,
  // meaning media.src/currentSrc is a blob: URL almost all the time.
  // The old code gated hover-attachment behind the same blob:/data:
  // exclusion used below for capture-state reset, which meant hover
  // previews (always blob:) rarely got the listener attached at all -
  // that was the actual cause of "download button doesn't show on
  // hover." Attaching the listener doesn't need a real URL, only the
  // DOM element; attachYouTubeHoverTarget() already no-ops on repeat
  // calls for the same element via its own __speusisHoverAttached flag.
  attachYouTubeHoverTarget(media);

  /* Do not clear the stream map from loadedmetadata. YouTube fires this
   * repeatedly while initializing MSE and when the player changes buffers;
   * the old reset made the panel appear briefly, then erase itself. The
   * yt-navigate-finish handler is the only navigation boundary that resets
   * a watch-page capture. */
  _ytActiveVideoKey = media.currentSrc || media.src || _ytActiveVideoKey;
}

function initYouTubePlayerHover() {
  if (!location.hostname.includes("youtube.com")) return;

  // Full navigation to a different video (real page swap via YouTube's SPA
  // router) is also a "new active video" — same reset, even before any
  // <video> loadedmetadata fires.
  let lastHref = location.href;
  document.addEventListener("yt-navigate-finish", () => {
    if (location.href === lastHref) return;
    lastHref = location.href;
    _ytActiveVideoKey = ""; // force the next loadedmetadata to re-attach/reset
    _ytHoverActive = false; // a real page navigation invalidates whatever was hovered before
    if (!isYouTubeVideoPage()) {
      _badgeHidden = false;
      resetYouTubeCaptureState();
      return;
    }

    /* yt-navigate-finish can fire after the new player's response has
     * already populated the list. Only reset when the URL proves this is a
     * different video; otherwise it erases the freshly detected formats. */
    const pageVideoId = getYouTubePageVideoId();
    if (pageVideoId && ytCurrentVideoId && pageVideoId !== ytCurrentVideoId) {
      resetYouTubeCaptureState();
    }
  });

  window.addEventListener("resize", positionBadgeOnYouTubePlayer, { passive: true });
  window.addEventListener("scroll", positionBadgeOnYouTubePlayer, { passive: true });
}

function getYouTubePageVideoId() {
  if (!location.hostname.includes("youtube.com")) return "";
  if (location.pathname.startsWith("/watch")) {
    return new URLSearchParams(location.search).get("v") || "";
  }
  const match = location.pathname.match(/^\/(?:shorts|live)\/([^/?]+)/);
  return match ? match[1] : "";
}

