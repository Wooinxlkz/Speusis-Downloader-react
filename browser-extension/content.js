/* ── Iframe awareness ──────────────────────────────────────────────
 * With "all_frames": true (added for cross-origin stream detection),
 * this whole script now also runs inside every iframe on the page,
 * not just the top document. A stream found inside a cross-origin
 * embed (Vimeo/Mux/Wistia-style players, ad-injected sources, etc.)
 * used to be completely invisible to detection before this. Rendering
 * the badge UI *inside* that iframe wouldn't work well - the iframe is
 * usually small and clipped - so subframes report up to the service
 * worker instead, which relays the detection to the page's top frame
 * to show in the one unified badge. Top-frame behavior (the common
 * case) is unchanged from before. */
const isTopFrame = window === window.top;

if (isTopFrame) {
  chrome.runtime.onMessage.addListener((message) => {
    if (message?.type === "speusis-subframe-stream-relay") {
      recordStream(message.url, message.streamType, message.encrypted);
    }
  });
}

/* ── AES-128 detection (detection only - decryption happens in the
 * desktop app's Rust downloader, not here) ────────────────────────── */
async function checkHlsEncryption(url) {
  try {
    const res = await fetch(url, { credentials: "include" });
    const text = await res.text();
    return /#EXT-X-KEY:METHOD=AES-128/i.test(text);
  } catch {
    return null; // unknown - CORS or network block, not necessarily unencrypted
  }
}

function checkStreamUrl(url, metadata) {
  if (!url || !url.startsWith("http")) return;
  try {
    const parsed = new URL(url);
    if (!STREAM_EXTS.test(parsed.pathname)) return;
    const type = detectStreamType(url);
    recordStream(url, type, undefined, metadata);
    if (type === "HLS") {
      checkHlsEncryption(url).then((encrypted) => {
        if (encrypted === null) return;
        markStreamEncrypted(url, encrypted);
      });
    }
  } catch {}
}

function detectStreamType(url) {
  if (/\.m3u8/i.test(url)) return "HLS";
  if (/\.mpd/i.test(url))  return "DASH";
  if (/\.m4s/i.test(url))  return "CMAF";
  return "Stream";
}

function recordStream(url, type, encrypted, metadata) {
  if (detectedStreams.has(url)) return;
  if (!isTopFrame) {
    // Report up instead of rendering a badge inside a (likely tiny,
    // clipped) cross-origin iframe. The top frame's listener above
    // relays this into its own detectedStreams / badge.
    detectedStreams.set(url, true); // dedupe guard for this frame only
    sendRuntimeMessage({
      type: "speusis-subframe-stream", url, streamType: type, encrypted,
    }).catch(() => {});
    return;
  }
  detectedStreams.set(url, { url, type, encrypted: encrypted ?? null, metadata: metadata || null, timestamp: Date.now() });
  updateStreamBadge();
}

function markStreamEncrypted(url, encrypted) {
  const info = detectedStreams.get(url);
  if (!info) return;
  info.encrypted = encrypted;
  if (isTopFrame) updateStreamBadge();
}

function recordYouTubeStream(url, itag, quality, kind, fileSize) {
  if (!isYouTubeVideoPage()) return;
  ytPendingFormats.delete(String(itag));
  if (kind === "video") {
    if (ytAdaptiveVideo.has(itag)) return;
    ytAdaptiveVideo.set(itag, { itag, quality, url, fileSize: fileSize || null });
    rebuildYouTubeMuxPairs();
    return;
  }
  if (kind === "audio") {
    if (ytAdaptiveAudio.has(itag)) return;
    ytAdaptiveAudio.set(itag, { itag, quality, url, fileSize: fileSize || null });
    rebuildYouTubeMuxPairs(); // an audio track just resolved — re-pair every known video itag
    return;
  }
  // "combined" (legacy progressive) or unspecified — original behavior.
  const key = `yt-itag-${itag}`;
  if (detectedStreams.has(key)) return;
  detectedStreams.set(key, { url, type: "MP4", quality, ytItag: itag, fileSize: fileSize || null, timestamp: Date.now() });
  updateStreamBadge();
}

