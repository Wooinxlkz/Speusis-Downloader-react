function wireBadgeDrag() {
  const handle = streamBadgeEl?.querySelector("#__speusis-drag-handle");
  if (!handle || handle.__speusisDragWired) return;
  handle.__speusisDragWired = true;
  handle.addEventListener("pointerdown", (event) => {
    if (!streamBadgeEl) return;
    event.preventDefault();
    const rect = streamBadgeEl.getBoundingClientRect();
    const offsetX = event.clientX - rect.left;
    const offsetY = event.clientY - rect.top;
    handle.setPointerCapture?.(event.pointerId);
    const move = (moveEvent) => {
      if (!streamBadgeEl) return;
      _badgeDragged = true;
      const maxLeft = Math.max(8, window.innerWidth - streamBadgeEl.offsetWidth - 8);
      const maxTop = Math.max(8, window.innerHeight - streamBadgeEl.offsetHeight - 8);
      const left = Math.max(8, Math.min(maxLeft, moveEvent.clientX - offsetX));
      const top = Math.max(8, Math.min(maxTop, moveEvent.clientY - offsetY));
      streamBadgeEl.style.left = `${Math.round(left)}px`;
      streamBadgeEl.style.top = `${Math.round(top)}px`;
      streamBadgeEl.style.right = "auto";
    };
    const end = () => {
      handle.removeEventListener("pointermove", move);
      handle.removeEventListener("pointerup", end);
      handle.removeEventListener("pointercancel", end);
      handle.releasePointerCapture?.(event.pointerId);
    };
    handle.addEventListener("pointermove", move);
    handle.addEventListener("pointerup", end);
    handle.addEventListener("pointercancel", end);
  });
}

